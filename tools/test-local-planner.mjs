import assert from 'node:assert/strict';
import { createLocalServer, academicOnly, currentPlanning } from './local-planner-server.mjs';
const common = currentPlanning(academicOnly({ major: 'undecided' }));
assert(common.eligibleOptions.every(option => option.category === 'core'));
const provisional = currentPlanning(academicOnly({ major: 'SD', current: ['BIT111'], currentTreatedAsPassed: ['BIT111', 'BIT242'] }));
assert.deepEqual(provisional.provisionalCurrentPasses, ['BIT111']);
assert.deepEqual(academicOnly({ name: 'Private Name', studentId: '123', email: 'private@example.com', passed: ['BIT108', 'Private Name'], major: 'SD' }).passed, ['BIT108']);
assert(!JSON.stringify(academicOnly({ name: 'Private Name', studentId: '123' })).includes('Private'));
const alerts = academicOnly({ studentKey: 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa', alerts: { error: [{ title: 'Prerequisites', details: 'BIT111 is required.', ignored: true }] } });
assert.equal(alerts.studentKey, 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa');
assert.deepEqual(alerts.alerts, { error: [{ title: 'Prerequisites', details: 'BIT111 is required.' }], warning: [], info: [] });
assert.deepEqual(academicOnly({}).alerts, { error: [], warning: [], info: [] });
const server = createLocalServer();
const port = Number(process.env.LOCAL_PLANNER_PORT || 8787);
await new Promise(resolve => server.listen(port, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${port}`;
let id = 0;
const rpc = async (method, params) => (await fetch(`${base}/mcp`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: ++id, method, params }) })).json();
try {
  const html = await (await fetch(base)).text();
  const token = html.match(/data-token="([a-f0-9]{64})"/)[1];
  assert.equal((await fetch(`${base}/tools/local-planner-server.mjs`)).status, 404);
  assert.equal((await fetch(`${base}/local-context`)).status, 403);
  const publish = (context, headers = {}) => fetch(`${base}/local-context`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Local-Planner-Token': token, ...headers }, body: JSON.stringify({ session: 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa', context }) });
  assert.equal((await publish({}, { Origin: 'https://evil.example' })).status, 403);
  assert.equal((await publish({}, { 'X-Local-Planner-Token': 'wrong' })).status, 403);
  const discovery = await rpc('tools/list');
  assert.equal(discovery.result.tools.length, 5);
  assert((await rpc('tools/call', { name: 'get_current_student_plan', arguments: {} })).result.isError);
  assert.equal((await publish({ passed: ['BIT108'], current: ['BIT111'], major: 'SD', name: 'Private Name', studentId: '123' })).status, 200);
  const result = await rpc('tools/call', { name: 'get_current_student_plan', arguments: {} });
  assert(!result.result.isError);
  assert(!JSON.stringify(result).includes('Private Name'));
  assert.deepEqual(JSON.parse(result.result.content[0].text).academicPlan.passed, ['BIT108']);
  const plan = await rpc('tools/call', { name: 'plan_subjects', arguments: { completed: [], major: 'SD' } });
  assert(!plan.result.isError);
  await publish(null);
  assert((await rpc('tools/call', { name: 'get_current_student_plan', arguments: {} })).result.isError);
  console.log('Passed local MCP discovery, academic-only context, sharing on/off, existing planning tools, origin/token checks and private-file protection.');
} finally { await new Promise(resolve => server.close(resolve)); }
